  function readStoredLang() {
    try { return localStorage.getItem('mc:lang'); } catch (e) { return null; }
  }
  function detectDefaultLang() {
    var nav = (navigator.language || 'ro').slice(0, 2).toLowerCase();
    return LANGS.indexOf(nav) >= 0 ? nav : 'ro';
  }
  var current = readStoredLang();
  if (LANGS.indexOf(current) < 0) current = detectDefaultLang();

  function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
  }
  function t(key, vars) {
    var dict = DICT[current] || DICT.ro;
    var str = dict[key];
    if (str == null) str = (DICT.ro[key] != null) ? DICT.ro[key] : key;
    return interpolate(str, vars);
  }
  function getLang() { return current; }
  function setLang(code) {
    if (LANGS.indexOf(code) < 0) return;
    current = code;
    try { localStorage.setItem('mc:lang', code); } catch (e) {}
    document.documentElement.setAttribute('lang', code);
    window.dispatchEvent(new CustomEvent('mc-lang-changed', { detail: { lang: code } }));
  }
  function localeTag(code) { return LOCALE_TAG[code || current] || 'ro-RO'; }

  document.documentElement.setAttribute('lang', current);

  // Small, reusable language-switcher control (a row of pill buttons). Reused
  // identically on index.html and match.html so both pages look/behave the
  // same; clicking a pill sets the language and reloads the page's own
  // render so the switch is immediate without a full page reload.
  function switcherEl(onChange) {
    var wrap = document.createElement('span');
    wrap.className = 'mc-lang-switch';
    wrap.setAttribute('role', 'group');
    wrap.setAttribute('aria-label', t('lang.label'));
    function draw() {
      wrap.innerHTML = '';
      LANGS.forEach(function (code) {
        var b = document.createElement('button');
        b.type = 'button';
        b.className = 'mc-lang-pill' + (code === current ? ' on' : '');
        b.textContent = code.toUpperCase();
        b.title = LANG_NAMES[code];
        b.onclick = function () {
          if (code === current) return;
          setLang(code);
          draw();
          if (onChange) onChange(code);
        };
        wrap.appendChild(b);
      });
    }
    draw();
    return wrap;
  }

  window.MC_I18N = {
    LANGS: LANGS.slice(), LANG_NAMES: LANG_NAMES,
    t: t, getLang: getLang, setLang: setLang, localeTag: localeTag,
    switcherEl: switcherEl
  };
